#define DTC_DETAIL_CAN_TX_TURBO UINT8_C(0xF7)
#define DTC_DETAIL_CAN_TX_THROTTLE UINT8_C(0xF8)
#define DTC_DETAIL_CAN_TX_OTHER UINT8_C(0xF0)
/** @} */
/** @} */

