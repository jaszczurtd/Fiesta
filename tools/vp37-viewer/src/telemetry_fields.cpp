const FieldInfo *find_field(std::string_view kind, std::string_view key) {
  if (kind == "T")
    kind = "C";
  for (const FieldInfo &field : kFields) {
    if (kind == field.kind && key == field.key)
      return &field;
  }
  return nullptr;
}

